class TradingState(str, Enum):
    OPEN = "OPEN"
    TRADING_PAUSED = "TRADING_PAUSED"  # docs: placement blocked, cancellation still available
    EXCHANGE_PAUSED = "EXCHANGE_PAUSED"  # docs: placement and cancellation both blocked
    MARKET_CLOSED = "MARKET_CLOSED"
    UNKNOWN = "UNKNOWN"


def trading_state(exchange_status: Mapping[str, Any] | None, market_status: str | None) -> TradingState:
    """From `GET /exchange/status` (`exchange_active`, `trading_active`) and the market's own status
    word. A missing or non-boolean field is UNKNOWN, never OPEN."""
    if not isinstance(exchange_status, Mapping):
        return TradingState.UNKNOWN
    exchange, trading = exchange_status.get("exchange_active"), exchange_status.get("trading_active")
    if exchange is False:
        return TradingState.EXCHANGE_PAUSED
    if trading is False:
        return TradingState.TRADING_PAUSED
    if exchange is not True or trading is not True or not isinstance(market_status, str):
        return TradingState.UNKNOWN
    if market_status.lower() in ("active", "open"):
        return TradingState.OPEN
    return TradingState.MARKET_CLOSED


