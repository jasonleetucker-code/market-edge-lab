# --------------------------------------------------------------------------- clocks


@dataclass(frozen=True)
class Stamps:
    """The four clocks of one message. None is unknown and is never filled in from another."""

    receipt_utc: str
    first_observed_utc: str
    processing_utc: str | None = None
    source_ts_utc: str | None = None

    def __post_init__(self) -> None:
        received, first = parse_utc(self.receipt_utc), parse_utc(self.first_observed_utc)
        if received is None or first is None:
            raise ValueError("receipt and first-observed times must be timezone-aware")
        if first > received:
            raise ValueError("first observation cannot be later than this copy's receipt")
        for name in ("processing_utc", "source_ts_utc"):
            value = getattr(self, name)
            if value is not None and parse_utc(value) is None:
                raise ValueError(f"{name} must be timezone-aware or None")


def _ms_to_utc(value: Any) -> str | None:
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        return None
    return datetime.fromtimestamp(value / 1000, tz=timezone.utc).isoformat()


def _sha(obj: Any) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, separators=(",", ":"), default=str).encode()).hexdigest()


# --------------------------------------------------------------------------- book messages


class MessageKind(str, Enum):
    SNAPSHOT = "SNAPSHOT"
    DELTA = "DELTA"


@dataclass(frozen=True)
class BookMessage:
    """One normalized order-book message. Levels are bids: (price in dollars, contracts)."""

    kind: MessageKind
    market_ticker: str
    sid: int | None
    seq: int | None
    stamps: Stamps
    raw_sha256: str
    yes_bids: tuple[tuple[Decimal, Decimal], ...] = ()  # SNAPSHOT only
    no_bids: tuple[tuple[Decimal, Decimal], ...] = ()
    side: str | None = None  # DELTA only: "yes" | "no"
    price: Decimal | None = None
    delta: Decimal | None = None


@dataclass(frozen=True)
class ParseFailure:
    reason: str
    detail: str
    receipt_utc: str
    raw_sha256: str


def _dec(value: Any) -> Decimal:
    try:
        out = Decimal(str(value))
    except (InvalidOperation, ValueError):
        raise ValueError(f"not a number: {value!r}") from None
    if not out.is_finite():
        raise ValueError(f"not finite: {value!r}")
    return out


def _count(value: Any, *, signed: bool) -> Decimal:
    out = _dec(value)
    if out % QUANTITY_STEP != 0:
        raise ValueError(f"count {out} is off the 0.01 contract step")
    if not signed and out < 0:
        raise ValueError(f"negative count {out}")
    return out


def _price(value: Any) -> Decimal:
    out = _dec(value)
    if not valid_price(out):
        raise ValueError(f"price {value!r} is not a dollar price strictly inside (0, 1) on the 1/100-cent grid")
    return out


def _levels(raw: Any) -> tuple[tuple[Decimal, Decimal], ...]:
    if raw is None:
        return ()
    if not isinstance(raw, list):
        raise ValueError("book side is not a list")
    out: dict[Decimal, Decimal] = {}
    for level in raw:
        if not isinstance(level, (list, tuple)) or len(level) != 2:
            raise ValueError(f"malformed level {level!r}")
        price, size = _price(level[0]), _count(level[1], signed=False)
        if size > 0:
            out[price] = out.get(price, Decimal(0)) + size
    return tuple(sorted(out.items()))


def parse_book_message(raw: Mapping[str, Any], *, receipt_utc: str, first_observed_utc: str | None = None,
                       processing_utc: str | None = None) -> BookMessage | ParseFailure:
    """Normalize one Kalshi websocket orderbook message as documented on 2026-09-28.

    Snapshot: `{"type": "orderbook_snapshot", "sid", "seq", "msg": {"market_ticker",
    "yes_dollars_fp": [[price, count]], "no_dollars_fp": [...]}}`. Delta: `{"type":
    "orderbook_delta", "sid", "seq", "msg": {"market_ticker", "price_dollars", "delta_fp", "side",
    "ts_ms"}}`. Prices are dollar strings ("0.4200"), counts fixed-point strings. Anything else,
    including a price in cents, is a `ParseFailure` that is kept, never a guess."""
    digest = _sha(raw)
    if parse_utc(receipt_utc) is None:
        raise ValueError("receipt_utc must be timezone-aware")

    def fail(reason: str, detail: str) -> ParseFailure:
        return ParseFailure(reason, detail, receipt_utc, digest)

    if not isinstance(raw, Mapping):
        return fail("NOT_AN_OBJECT", type(raw).__name__)
    kind = {"orderbook_snapshot": MessageKind.SNAPSHOT, "orderbook_delta": MessageKind.DELTA}.get(raw.get("type"))
    if kind is None:
        return fail("UNKNOWN_TYPE", str(raw.get("type")))
    body = raw.get("msg")
    if not isinstance(body, Mapping) or not isinstance(body.get("market_ticker"), str) or not body["market_ticker"]:
        return fail("NO_MARKET", "msg.market_ticker is missing")
    sid, seq = raw.get("sid"), raw.get("seq")
    sid = sid if isinstance(sid, int) and not isinstance(sid, bool) else None
    seq = seq if isinstance(seq, int) and not isinstance(seq, bool) and seq >= 0 else None
    stamps = Stamps(receipt_utc=receipt_utc, first_observed_utc=first_observed_utc or receipt_utc,
                    processing_utc=processing_utc, source_ts_utc=_ms_to_utc(body.get("ts_ms")))
    try:
        if kind is MessageKind.SNAPSHOT:
            return BookMessage(kind, body["market_ticker"], sid, seq, stamps, digest,
                               yes_bids=_levels(body.get("yes_dollars_fp")), no_bids=_levels(body.get("no_dollars_fp")))
        side = body.get("side")
        if side not in BOOK_SIDES:
            return fail("BAD_SIDE", repr(side))
        delta = _count(body.get("delta_fp"), signed=True)
        if delta == 0:
            return fail("ZERO_DELTA", "a delta of 0 contracts changes nothing and is not documented")
        return BookMessage(kind, body["market_ticker"], sid, seq, stamps, digest, side=side,
                           price=_price(body.get("price_dollars")), delta=delta)
    except ValueError as exc:
        return fail("BAD_VALUE", str(exc))


# --------------------------------------------------------------------------- reconstruction


class BookStatus(str, Enum):
    NO_VALID_START = "NO_VALID_START"  # no snapshot yet: unusable
    VALID = "VALID"
    GAP_AWAITING_RESYNC = "GAP_AWAITING_RESYNC"  # a sequence gap or a foreign sid: unusable until a snapshot
    INVALID_AWAITING_RESYNC = "INVALID_AWAITING_RESYNC"  # negative level or crossed book: unusable


UNUSABLE = frozenset({BookStatus.NO_VALID_START, BookStatus.GAP_AWAITING_RESYNC, BookStatus.INVALID_AWAITING_RESYNC})


class Applied(str, Enum):
    SNAPSHOT_APPLIED = "SNAPSHOT_APPLIED"
    RESYNCED = "RESYNCED"  # a snapshot that ended an unusable period
    DELTA_APPLIED = "DELTA_APPLIED"
    IGNORED_BEFORE_START = "IGNORED_BEFORE_START"
    IGNORED_DUPLICATE = "IGNORED_DUPLICATE"
    IGNORED_WHILE_UNUSABLE = "IGNORED_WHILE_UNUSABLE"
    GAP_DETECTED = "GAP_DETECTED"
    SNAPSHOT_WITHOUT_SEQ = "SNAPSHOT_WITHOUT_SEQ"
    DELTA_WITHOUT_SEQ = "DELTA_WITHOUT_SEQ"
    NEGATIVE_LEVEL = "NEGATIVE_LEVEL"
    CROSSED_BOOK = "CROSSED_BOOK"
    WRONG_MARKET = "WRONG_MARKET"
    GAP_ON_SUBSCRIPTION = "GAP_ON_SUBSCRIPTION"  # another market's message revealed a gap on this book's sid
    SEQ_SCOPE_CONFLICT = "SEQ_SCOPE_CONFLICT"  # one (sid, seq) carried two different messages: scope assumption wrong
    SHARED_SUBSCRIPTION = "SHARED_SUBSCRIPTION"  # MARKET scope: a sid carried a second market


@dataclass(frozen=True)
class BookState:
    """The reconstructed book of one market, after the messages applied so far."""

    market_ticker: str
    status: BookStatus = BookStatus.NO_VALID_START
    sid: int | None = None
    last_seq: int | None = None
    yes_bids: tuple[tuple[Decimal, Decimal], ...] = ()
    no_bids: tuple[tuple[Decimal, Decimal], ...] = ()
    valid_since_utc: str | None = None  # receipt of the snapshot that started the valid period
    last_receipt_utc: str | None = None  # the last message that touched this book, whatever it did
    last_applied_receipt_utc: str | None = None
    # the venue stamp of the message last applied (the one received at last_applied_receipt_utc); None when that
    # message carried none. An earlier message's stamp is never carried to later content, least of all across a resync.
    last_source_ts_utc: str | None = None
    counts: tuple[tuple[str, int], ...] = ()

    @property
    def usable(self) -> bool:
        return self.status is BookStatus.VALID

    def count(self, what: Applied) -> int:
        return dict(self.counts).get(what.value, 0)

    def best_yes_bid(self) -> tuple[Decimal, Decimal] | None:
        return self.yes_bids[-1] if self.usable and self.yes_bids else None

    def best_no_bid(self) -> tuple[Decimal, Decimal] | None:
        return self.no_bids[-1] if self.usable and self.no_bids else None


@dataclass(frozen=True)
class Transition:
    state: BookState
    applied: Applied
    detail: str


def _bump(counts: tuple[tuple[str, int], ...], what: Applied) -> tuple[tuple[str, int], ...]:
    d = dict(counts)
    d[what.value] = d.get(what.value, 0) + 1
    return tuple(sorted(d.items()))


def _crossed(yes: Sequence[tuple[Decimal, Decimal]], no: Sequence[tuple[Decimal, Decimal]]) -> bool:
    return bool(yes and no and yes[-1][0] + no[-1][0] >= 1)


def apply_message(state: BookState, msg: BookMessage) -> Transition:
    """The book after `msg`. Pure: `state` is not changed."""
    seen = replace(state, last_receipt_utc=msg.stamps.receipt_utc)

    def done(new: BookState, what: Applied, detail: str) -> Transition:
        return Transition(replace(new, counts=_bump(new.counts, what)), what, detail)

    if msg.market_ticker != state.market_ticker:
        return done(replace(state), Applied.WRONG_MARKET, f"{msg.market_ticker} is not {state.market_ticker}")
    if msg.kind is MessageKind.SNAPSHOT:
        if msg.seq is None or msg.sid is None:
            return done(replace(seen, status=BookStatus.GAP_AWAITING_RESYNC), Applied.SNAPSHOT_WITHOUT_SEQ,
                        "a snapshot without sid/seq cannot start a sequenced book")
        was_unusable = state.status is not BookStatus.VALID and state.status is not BookStatus.NO_VALID_START
        new = replace(seen, sid=msg.sid, last_seq=msg.seq, yes_bids=msg.yes_bids, no_bids=msg.no_bids,
                      valid_since_utc=msg.stamps.receipt_utc, last_applied_receipt_utc=msg.stamps.receipt_utc,
                      last_source_ts_utc=msg.stamps.source_ts_utc)
        if _crossed(msg.yes_bids, msg.no_bids):
            return done(replace(new, status=BookStatus.INVALID_AWAITING_RESYNC, valid_since_utc=None),
                        Applied.CROSSED_BOOK, "snapshot is crossed: best yes bid + best no bid >= 1")
        return done(replace(new, status=BookStatus.VALID),
                    Applied.RESYNCED if was_unusable else Applied.SNAPSHOT_APPLIED, f"sid {msg.sid} seq {msg.seq}")
    # delta
    if state.status is BookStatus.NO_VALID_START:
        return done(seen, Applied.IGNORED_BEFORE_START, "no snapshot yet")
    if state.status is not BookStatus.VALID:
        return done(seen, Applied.IGNORED_WHILE_UNUSABLE, f"book is {state.status.value}")
    if msg.seq is None:
        return done(replace(seen, status=BookStatus.GAP_AWAITING_RESYNC, valid_since_utc=None),
                    Applied.DELTA_WITHOUT_SEQ, "a delta without seq cannot be ordered")
    if msg.sid != state.sid:
        return done(replace(seen, status=BookStatus.GAP_AWAITING_RESYNC, valid_since_utc=None), Applied.GAP_DETECTED,
                    f"delta from sid {msg.sid}, book is sid {state.sid}")
    if msg.seq <= state.last_seq:
        return done(seen, Applied.IGNORED_DUPLICATE, f"seq {msg.seq} <= last applied {state.last_seq}")
    if msg.seq != state.last_seq + 1:
        return done(replace(seen, status=BookStatus.GAP_AWAITING_RESYNC, valid_since_utc=None), Applied.GAP_DETECTED,
                    f"expected seq {state.last_seq + 1}, got {msg.seq}")
    levels = dict(state.yes_bids if msg.side == "yes" else state.no_bids)
    size = levels.get(msg.price, Decimal(0)) + msg.delta
    if size < 0:
        return done(replace(seen, status=BookStatus.INVALID_AWAITING_RESYNC, valid_since_utc=None, last_seq=msg.seq),
                    Applied.NEGATIVE_LEVEL, f"{msg.side} {msg.price} would hold {size}")
    if size == 0:
        levels.pop(msg.price, None)
    else:
        levels[msg.price] = size
    side_levels = tuple(sorted(levels.items()))
    yes = side_levels if msg.side == "yes" else state.yes_bids
    no = side_levels if msg.side == "no" else state.no_bids
    new = replace(seen, last_seq=msg.seq, yes_bids=yes, no_bids=no, last_applied_receipt_utc=msg.stamps.receipt_utc,
                  last_source_ts_utc=msg.stamps.source_ts_utc)
    if _crossed(yes, no):
        return done(replace(new, status=BookStatus.INVALID_AWAITING_RESYNC, valid_since_utc=None), Applied.CROSSED_BOOK,
                    "delta crossed the book")
    return done(new, Applied.DELTA_APPLIED, f"seq {msg.seq}")


def reconstruct(market_ticker: str, messages: Iterable[BookMessage]) -> tuple[BookState, tuple[Transition, ...]]:
    """Apply `messages` in arrival order; return the final state and every transition."""
    state, out = BookState(market_ticker), []
    for msg in messages:
        t = apply_message(state, msg)
        out.append(t)
        state = t.state
    return state, tuple(out)


class SeqScope(str, Enum):
    """What `seq` counts. The docs say only that it guarantees "you received all the messages" of the
    subscription; whether it runs per subscription across several markets or per market is UNVERIFIED.

    - SUBSCRIPTION (default): one counter per `sid` across every market it carries. A gap seen on any
      market makes every book on that sid unusable until each is resynced.
    - MARKET: one counter per market. Safe only with one market per subscription, where both readings
      coincide; a sid that carries a second market makes both books unusable (SHARED_SUBSCRIPTION)."""

    SUBSCRIPTION = "SUBSCRIPTION"
    MARKET = "MARKET"


RECENT_SEQ_WINDOW = 4096  # (sid, seq) -> message digest kept for conflict detection


class SubscriptionReconstructor:
    """Books for every market in one journal, sequenced under a declared `SeqScope`.

    In memory and deterministic; it never opens anything. Under SUBSCRIPTION scope a repeated
    (sid, seq) with a *different* message is a SEQ_SCOPE_CONFLICT: the per-subscription reading is
    wrong for this feed, so every book on that sid becomes unusable rather than silently dropping one
    market's updates as duplicates."""

    def __init__(self, scope: SeqScope = SeqScope.SUBSCRIPTION) -> None:
        self.scope = scope
        self.books: dict[str, BookState] = {}
        self.transitions: dict[str, list[Transition]] = {}
        self._sid_last: dict[int, int] = {}
        self._recent: dict[int, dict[int, str]] = {}
        self._sid_markets: dict[int, set[str]] = {}

    def _record(self, ticker: str, t: Transition) -> None:
        self.books[ticker] = t.state
        self.transitions.setdefault(ticker, []).append(t)

    def _book(self, ticker: str) -> BookState:
        return self.books.get(ticker) or BookState(ticker)

    def _unusable(self, ticker: str, msg: BookMessage, what: Applied, status: BookStatus, detail: str) -> None:
        s = self._book(ticker)
        new = replace(s, status=status, valid_since_utc=None, last_receipt_utc=msg.stamps.receipt_utc,
                      counts=_bump(s.counts, what))
        self._record(ticker, Transition(new, what, detail))

    def _poison_sid(self, sid: int, msg: BookMessage, what: Applied, status: BookStatus, detail: str,
                    *, skip: str | None = None) -> None:
        for ticker, s in list(self.books.items()):
            if ticker != skip and s.sid == sid and s.status is BookStatus.VALID:
                self._unusable(ticker, msg, what, status, detail)

    def apply(self, msg: BookMessage) -> None:
        ticker, sid, seq = msg.market_ticker, msg.sid, msg.seq
        if self.scope is SeqScope.MARKET:
            if sid is not None:
                markets = self._sid_markets.setdefault(sid, set())
                markets.add(ticker)
                if len(markets) > 1:
                    for other in sorted(markets):
                        self._unusable(other, msg, Applied.SHARED_SUBSCRIPTION, BookStatus.GAP_AWAITING_RESYNC,
                                       f"sid {sid} carries {sorted(markets)}: MARKET scope needs one market per "
                                       "subscription")
                    return
            self._record(ticker, apply_message(self._book(ticker), msg))
            return
        if sid is None or seq is None:  # the per-market rules already refuse these
            self._record(ticker, apply_message(self._book(ticker), msg))
            return
        recent = self._recent.setdefault(sid, {})
        last = self._sid_last.get(sid)
        if last is not None and seq <= last:
            seen = recent.get(seq)
            if seen is not None and seen != msg.raw_sha256:
                detail = f"sid {sid} seq {seq} carried two different messages: seq is not per subscription here"
                self._poison_sid(sid, msg, Applied.SEQ_SCOPE_CONFLICT, BookStatus.INVALID_AWAITING_RESYNC, detail,
                                 skip=ticker)
                self._unusable(ticker, msg, Applied.SEQ_SCOPE_CONFLICT, BookStatus.INVALID_AWAITING_RESYNC, detail)
                return
            s = self._book(ticker)
            self._record(ticker, Transition(replace(s, last_receipt_utc=msg.stamps.receipt_utc,
                                                    counts=_bump(s.counts, Applied.IGNORED_DUPLICATE)),
                                            Applied.IGNORED_DUPLICATE, f"sid {sid} seq {seq} <= {last}"))
            return
        gap = last is not None and seq != last + 1
        self._sid_last[sid] = seq
        recent[seq] = msg.raw_sha256
        if len(recent) > RECENT_SEQ_WINDOW:
            for old in sorted(recent)[: len(recent) - RECENT_SEQ_WINDOW]:
                del recent[old]
        if gap:
            detail = f"sid {sid}: expected seq {last + 1}, got {seq}"
            self._poison_sid(sid, msg, Applied.GAP_ON_SUBSCRIPTION, BookStatus.GAP_AWAITING_RESYNC, detail, skip=ticker)
        s = self._book(ticker)
        if msg.kind is MessageKind.SNAPSHOT:
            self._record(ticker, apply_message(s, msg))  # a snapshot starts (or restarts) this market's book
            return
        if gap:
            self._unusable(ticker, msg, Applied.GAP_DETECTED, BookStatus.GAP_AWAITING_RESYNC
                           if s.status is not BookStatus.NO_VALID_START else BookStatus.NO_VALID_START, detail)
            return
        if s.status is BookStatus.VALID and s.sid == sid:
            # contiguous on the subscription: present it to the per-market rules as the next seq
            self._record(ticker, apply_message(replace(s, last_seq=seq - 1), msg))
        else:
            self._record(ticker, apply_message(s, msg))  # before start, unusable, or another sid: per-market rules


def reconstruct_many(messages: Iterable[BookMessage], *, scope: SeqScope = SeqScope.SUBSCRIPTION
                     ) -> tuple[dict[str, BookState], dict[str, tuple[Transition, ...]]]:
    """Every market's book from one journal's messages, in arrival order, under `scope`."""
    r = SubscriptionReconstructor(scope)
    for msg in messages:
        r.apply(msg)
    return dict(r.books), {k: tuple(v) for k, v in r.transitions.items()}


# --------------------------------------------------------------------------- REST snapshots (route B)


@dataclass(frozen=True)
class RestSnapshot:
    """One polled REST order book. It has no sequence number and no venue timestamp
    (docs: the orderbook response schema carries neither), so each poll stands alone and
    nothing between two polls is known."""

    market_ticker: str
    yes_bids: tuple[tuple[Decimal, Decimal], ...]
    no_bids: tuple[tuple[Decimal, Decimal], ...]
    stamps: Stamps
    depth_limit: int | None  # the `depth` requested; None = all levels
    raw_sha256: str
    anomaly: str | None = None

    @property
    def truncated_yes(self) -> bool:
        return self.depth_limit is not None and len(self.yes_bids) >= self.depth_limit


def rest_snapshot(market_ticker: str, payload: Mapping[str, Any], *, receipt_utc: str, depth_limit: int | None,
                  first_observed_utc: str | None = None) -> RestSnapshot:
    """Normalize `GET /markets/{ticker}/orderbook` (`{"orderbook_fp": {"yes_dollars", "no_dollars"}}`).
    A malformed or crossed book keeps `anomaly` and no levels; it is never repaired."""
    stamps = Stamps(receipt_utc=receipt_utc, first_observed_utc=first_observed_utc or receipt_utc)
    book = payload.get("orderbook_fp") if isinstance(payload, Mapping) else None
    digest = _sha(payload)
    if not isinstance(book, Mapping):
        return RestSnapshot(market_ticker, (), (), stamps, depth_limit, digest, "NO_BOOK")
    try:
        yes, no = _levels(book.get("yes_dollars")), _levels(book.get("no_dollars"))
    except ValueError as exc:
        return RestSnapshot(market_ticker, (), (), stamps, depth_limit, digest, f"MALFORMED: {exc}")
    if _crossed(yes, no):
        return RestSnapshot(market_ticker, (), (), stamps, depth_limit, digest, "CROSSED")
    return RestSnapshot(market_ticker, yes, no, stamps, depth_limit, digest)


# --------------------------------------------------------------------------- selling into the bids


@dataclass(frozen=True)
class SaleWalk:
    """What selling `quantity` contracts of one side into its bids would receive, before fees.

    Built on `opportunity.walk_ladder`: selling YES into YES bids at b is the mirror of taking
    NO asks at 1 - b, so the walk reuses the canonical depth walk and never prices a partial
    fill by accident. `levels` are (sale price, size) from the best bid down."""

    status: DepthStatus
    quantity: Decimal
    available: Decimal | None
    levels: tuple[tuple[Decimal, Decimal], ...]
    gross_proceeds: Decimal | None
    worst_price: Decimal | None
    detail: str


def walk_bids(bids: Sequence[tuple[Decimal, Decimal]], quantity: Decimal, *, min_price: Decimal | None = None,
              truncated: bool = False, market_id: str = "", side: str = "YES") -> SaleWalk:
    """Sell `quantity` into `bids` (ascending (price, size), as stored), best first, never below
    `min_price` (a limit). Bids below the limit are not offered to the walk."""
    eligible = [(p, s) for p, s in bids if s > 0 and (min_price is None or p >= min_price)]
    # A limit hides the deeper bids, so running out is a real shortfall, not unknown depth.
    hidden_by_limit = min_price is not None and len(eligible) < len([b for b in bids if b[1] > 0])
    mirror = DepthLadder("kalshi", market_id, "NO" if side == "YES" else "YES",
                         tuple(DepthLevel(Decimal(1) - p, s) for p, s in sorted(eligible, reverse=True)),
                         truncated and not hidden_by_limit, None, None, None)
    fill = walk_ladder(mirror, quantity)
    if fill.status is not DepthStatus.FILLABLE:
        return SaleWalk(fill.status, fill.quantity, fill.available, (), None, None, fill.detail)
    levels = tuple((Decimal(1) - t.price, t.size) for t in fill.takes)
    return SaleWalk(fill.status, fill.quantity, fill.available, levels, fill.quantity - fill.gross_cost,
                    Decimal(1) - fill.limit_price, fill.detail)


def depth_at_or_above(bids: Sequence[tuple[Decimal, Decimal]], price: Decimal) -> Decimal:
    return sum((s for p, s in bids if p >= price), Decimal(0))


