class Phase(str, Enum):
    PREGAME = "PREGAME"
    LIVE = "LIVE"
    BREAK = "BREAK"  # halftime, intermission, a review stoppage
    POSTGAME = "POSTGAME"
    UNKNOWN = "UNKNOWN"


