# Fixed rule strengths. They are selection confidences of a rule, not probabilities.
RULE_MATCH_STRENGTH = Decimal("1")
RULE_ABSENCE_STRENGTH = Decimal("0.5")

# Wording that makes a contract clause need human review. A rule match only queues a clause for review.
AMBIGUITY_MARKERS = (
    r"\bapproximately\b", r"\babout\b", r"\bat (?:its|the) (?:sole )?discretion\b", r"\bmay\b",
    r"\bor similar\b", r"\bincluding but not limited to\b", r"\btbd\b", r"\bto be determined\b",
    r"\bsubstantially\b", r"\breasonabl[ey]\b", r"\bcomparable\b", r"\bor other\b",
)
_AMBIGUITY = tuple(re.compile(p, re.IGNORECASE) for p in AMBIGUITY_MARKERS)

NON_GENERATIVE_THRESHOLDS: Mapping[str, Decimal] = MappingProxyType({
    "relevant_min": Decimal("0.6"), "not_relevant_max": Decimal("0.2"),
    "duplicate_min": Decimal("0.85"), "original_max": Decimal("0.3"),
})
_STOPWORDS = frozenset({"a", "an", "and", "are", "as", "at", "be", "by", "for", "from", "in", "is", "it", "of", "on",
                        "or", "that", "the", "this", "to", "was", "will", "with"})


def tokens(text: str | None) -> frozenset[str]:
    """Case-folded alphanumeric tokens without stopwords. Deterministic and order-free."""
    if not text:
        return frozenset()
    return frozenset(t for t in re.findall(r"[0-9a-z]+", text.casefold()) if t not in _STOPWORDS)


def _q(value: Decimal) -> Decimal:
    return value.quantize(CONFIDENCE_QUANTUM, rounding=ROUND_HALF_EVEN)


def _answer(label: str, candidate: str | None, confidence: Decimal, cited: Sequence[str]) -> dict:
    return {"decision": "ANSWER", "label": label, "candidate_id": candidate, "selection_confidence": _q(confidence),
            "evidence_ids": list(cited), "abstain_reason": None}


def _abstain(reason: AbstainReason, cited: Sequence[str] = ()) -> dict:
    return {"decision": "ABSTAIN", "label": None, "candidate_id": None, "selection_confidence": None,
            "evidence_ids": list(cited), "abstain_reason": reason.value}


def _sorted_candidates(request: SemanticRequest) -> list[Candidate]:
    return sorted(request.candidates, key=lambda c: c.candidate_id)  # never presentation order


def _local(raw: dict) -> ProviderResponse:
    return ProviderResponse(raw, CostBasis(CostKind.LOCAL_DETERMINISTIC))


def rules_baseline(request: SemanticRequest) -> ProviderResponse:
    """Deterministic rules over structured fields only (`keys`, `claims`, hashes) and, for TERM_AMBIGUITY, the
    contract clause text. Retrieved evidence text is never read, so an instruction inside it changes nothing."""
    if request.provider is not Provider.RULES_BASELINE:
        raise ValueError("rules_baseline answers RULES_BASELINE requests only")
    subject, cited = request.subject, [request.subject_evidence_id]
    candidates = _sorted_candidates(request)
    if request.task is Task.RELEVANCE:
        if not subject.keys:
            return _local(_abstain(AbstainReason.INSUFFICIENT_EVIDENCE, cited))
        hits = [c.candidate_id for c in candidates if c.keys & subject.keys]
        if len(hits) == 1:
            return _local(_answer("RELEVANT", hits[0], RULE_MATCH_STRENGTH, cited))
        if hits:
            return _local(_abstain(AbstainReason.AMBIGUOUS, cited))
        return _local(_answer("NOT_RELEVANT", None, RULE_ABSENCE_STRENGTH, cited))
    if request.task is Task.DUPLICATE:
        story = {k for k in subject.keys if k.startswith("story:")}
        hits = [c.candidate_id for c in candidates
                if c.ref_sha256 == subject.content_sha256 or (story and story & c.keys)]
        if len(hits) == 1:
            return _local(_answer("DUPLICATE", hits[0], RULE_MATCH_STRENGTH, cited))
        reason = AbstainReason.AMBIGUOUS if hits else AbstainReason.INSUFFICIENT_EVIDENCE
        return _local(_abstain(reason, cited))  # rules cannot prove a story is original
    if request.task is Task.CONTRADICTION:
        mine: dict[str, set[str]] = {}
        for key, value in subject.claims:
            mine.setdefault(key, set()).add(value)
        conflicts, shared = [], False
        for c in candidates:
            overlap = [(k, v) for k, v in c.claims if k in mine]
            shared = shared or bool(overlap)
            if any(v not in mine[k] for k, v in overlap):
                conflicts.append(c.candidate_id)
        if len(conflicts) == 1:
            return _local(_answer("CONTRADICTION_NEEDS_HUMAN", conflicts[0], RULE_MATCH_STRENGTH, cited))
        if conflicts:
            return _local(_abstain(AbstainReason.AMBIGUOUS, cited))
        if shared:
            return _local(_answer("NO_CONTRADICTION_FOUND", None, RULE_ABSENCE_STRENGTH, cited))
        return _local(_abstain(AbstainReason.INSUFFICIENT_EVIDENCE, cited))
    flagged = [c.candidate_id for c in candidates if any(p.search(c.text) for p in _AMBIGUITY)]
    if len(flagged) == 1:
        return _local(_answer("AMBIGUOUS_NEEDS_REVIEW", flagged[0], RULE_MATCH_STRENGTH, cited))
    if flagged:
        return _local(_abstain(AbstainReason.AMBIGUOUS, cited))
    return _local(_answer("NO_AMBIGUITY_FLAGGED", None, RULE_ABSENCE_STRENGTH, cited))


def non_generative_baseline(request: SemanticRequest) -> ProviderResponse:
    """Token overlap with fixed thresholds (`NON_GENERATIVE_THRESHOLDS`). RELEVANCE uses containment of each
    candidate's tokens in the subject text, which added text can only raise by repeating a candidate's own words.
    DUPLICATE uses Jaccard similarity. CONTRADICTION and TERM_AMBIGUITY are out of its reach: it abstains."""
    if request.provider is not Provider.NON_GENERATIVE_BASELINE:
        raise ValueError("non_generative_baseline answers NON_GENERATIVE_BASELINE requests only")
    cited = [request.subject_evidence_id]
    if request.task in (Task.CONTRADICTION, Task.TERM_AMBIGUITY):
        return _local(_abstain(AbstainReason.UNSUPPORTED_TASK, cited))
    mine = tokens(request.subject.text)
    if not mine:
        return _local(_abstain(AbstainReason.INSUFFICIENT_EVIDENCE, cited))
    scores = []
    for c in _sorted_candidates(request):
        theirs = tokens(c.text)
        if not theirs:
            continue
        if request.task is Task.RELEVANCE:
            scores.append((Decimal(len(theirs & mine)) / Decimal(len(theirs)), c.candidate_id))
        else:
            scores.append((Decimal(len(theirs & mine)) / Decimal(len(theirs | mine)), c.candidate_id))
    if not scores:
        return _local(_abstain(AbstainReason.INSUFFICIENT_EVIDENCE, cited))
    best = max(s for s, _ in scores)
    leaders = [cid for s, cid in scores if s == best]
    hi, lo = (("relevant_min", "not_relevant_max") if request.task is Task.RELEVANCE
              else ("duplicate_min", "original_max"))
    positive, negative = (("RELEVANT", "NOT_RELEVANT") if request.task is Task.RELEVANCE
                          else ("DUPLICATE", "ORIGINAL"))
    if best >= NON_GENERATIVE_THRESHOLDS[hi] and len(leaders) == 1:
        return _local(_answer(positive, leaders[0], best, cited))
    if best < NON_GENERATIVE_THRESHOLDS[lo]:
        return _local(_answer(negative, None, Decimal(1) - best, cited))
    return _local(_abstain(AbstainReason.AMBIGUOUS, cited))


def judge_with_baseline(request: SemanticRequest) -> SemanticResult:
    """Run the request's baseline and validate it through the same path as any responder. No model is called."""
    responders = {Provider.RULES_BASELINE: rules_baseline, Provider.NON_GENERATIVE_BASELINE: non_generative_baseline}
    if request.provider not in responders:
        raise ValueError(f"{request.provider.value} is not a local baseline")
    early = preflight(request)
    return early if early is not None else validate_response(request, responders[request.provider](request))
