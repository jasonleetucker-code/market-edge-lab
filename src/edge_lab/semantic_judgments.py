class Outcome(str, Enum):
    CORRECT = "CORRECT"
    HARMFUL_ERROR = "HARMFUL_ERROR"
    BENIGN_ERROR = "BENIGN_ERROR"
    NOT_COVERED = "NOT_COVERED"


@dataclass(frozen=True)
class Adjudication:
    """A human's answer for one question. `adjudicator` is a role id; fixtures use "FIXTURE"."""

    request_hash: str
    label: str
    candidate_id: str | None
    adjudicator: str

    def __post_init__(self) -> None:
        _require_sha(self.request_hash, "request_hash")
        _require_id(self.adjudicator, "adjudicator")


def score(result: SemanticResult, adjudication: Adjudication, threshold: Decimal | None = None) -> Outcome:
    if adjudication.request_hash != result.request_hash:
        raise ValueError("adjudication is for another request")
    if result.status is not Status.ACCEPTED or (threshold is not None and result.selection_confidence < threshold):
        return Outcome.NOT_COVERED
    if (result.label, result.candidate_id) == (adjudication.label, adjudication.candidate_id):
        return Outcome.CORRECT
    harmful = TASK_SPECS[result.task].harmful_when_wrong
    return Outcome.HARMFUL_ERROR if result.label in harmful else Outcome.BENIGN_ERROR


@dataclass(frozen=True)
class CurvePoint:
    threshold: Decimal
    total: int
    covered: int
    correct: int
    harmful: int
    benign: int

    @property
    def coverage(self) -> Decimal | None:
        return None if self.total == 0 else Decimal(self.covered) / Decimal(self.total)

    @property
    def harmful_rate(self) -> Decimal | None:
        """Harmful errors per question asked (abstentions included in the denominator)."""
        return None if self.total == 0 else Decimal(self.harmful) / Decimal(self.total)


@dataclass(frozen=True)
class CoverageCurve:
    points: tuple[CurvePoint, ...]
    evidence_class: EvidenceClass = RESULT_EVIDENCE_CLASS
    notice: str = FIXTURE_NOTICE

    def __post_init__(self) -> None:
        if self.evidence_class is not RESULT_EVIDENCE_CLASS:
            raise ValueError("a coverage curve of this tranche is FIXTURE")


def coverage_harmful_error_curve(results: Sequence[SemanticResult],
                                 adjudications: Iterable[Adjudication]) -> CoverageCurve:
    """Coverage against harmful-error rate as the acceptance threshold rises. Every result needs a human
    adjudication: a missing one is an error, never a silent correct."""
    by_request: dict[str, Adjudication] = {}
    for adj in adjudications:
        if adj.request_hash in by_request:
            raise ValueError(f"two adjudications for {adj.request_hash}")
        by_request[adj.request_hash] = adj
    missing = sorted({r.request_hash for r in results} - set(by_request))
    if missing:
        raise ValueError(f"{len(missing)} result(s) have no adjudication")
    thresholds = sorted({r.selection_confidence for r in results if r.status is Status.ACCEPTED}, reverse=True)
    points = []
    for t in thresholds:
        outcomes = [score(r, by_request[r.request_hash], t) for r in results]
        points.append(CurvePoint(
            threshold=t, total=len(results), covered=sum(o is not Outcome.NOT_COVERED for o in outcomes),
            correct=outcomes.count(Outcome.CORRECT), harmful=outcomes.count(Outcome.HARMFUL_ERROR),
            benign=outcomes.count(Outcome.BENIGN_ERROR)))
    return CoverageCurve(tuple(points))


