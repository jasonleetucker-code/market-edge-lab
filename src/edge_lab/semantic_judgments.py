@dataclass(frozen=True)
class CostBasis:
    """What a response cost and on what basis. Unknown stays None; a known zero is Decimal("0")."""

    kind: CostKind
    model_calls: int = 0
    input_tokens: int | None = None
    output_tokens: int | None = None
    monetary_usd: Decimal | None = None

    def __post_init__(self) -> None:
        if not isinstance(self.kind, CostKind):
            raise SemanticValidationError(Rejection.BAD_TYPE, "kind must be a CostKind")
        for name, value in (("model_calls", self.model_calls), ("input_tokens", self.input_tokens),
                            ("output_tokens", self.output_tokens)):
            if value is not None and (isinstance(value, bool) or not isinstance(value, int) or value < 0):
                raise SemanticValidationError(Rejection.BAD_TYPE, f"{name} must be a non-negative integer")
        if self.monetary_usd is not None and (not isinstance(self.monetary_usd, Decimal)
                                              or not self.monetary_usd.is_finite() or self.monetary_usd < 0):
            raise SemanticValidationError(Rejection.BAD_TYPE, "monetary_usd must be a finite Decimal >= 0")
        if self.kind is not CostKind.PROVIDER_METERED:
            if self.model_calls != 0:
                raise SemanticValidationError(Rejection.BAD_TYPE, f"{self.kind.value} makes no model call")
            if self.monetary_usd is None:
                object.__setattr__(self, "monetary_usd", Decimal("0"))  # nothing was bought: a known zero
            elif self.monetary_usd != 0:
                raise SemanticValidationError(Rejection.BAD_TYPE, f"{self.kind.value} costs nothing")

    def to_dict(self) -> dict:
        return {"kind": self.kind.value, "model_calls": self.model_calls, "input_tokens": self.input_tokens,
                "output_tokens": self.output_tokens,
                "monetary_usd": None if self.monetary_usd is None else str(self.monetary_usd)}


@dataclass(frozen=True)
class ProviderResponse:
    """What came back. `raw_output` is untrusted: a JSON text, bytes or a mapping, validated by `validate_response`.
    `latency_ms` None means unmeasured."""

    raw_output: Any
    cost: CostBasis
    latency_ms: int | None = None
    timed_out: bool = False
    error: str | None = None


def scripted_response(raw_output: Any, *, latency_ms: int | None = None, timed_out: bool = False,
                      error: str | None = None) -> ProviderResponse:
    """A FIXTURE response: a test wrote it, nothing ran."""
    return ProviderResponse(raw_output, CostBasis(CostKind.NO_MODEL_CALL), latency_ms, timed_out, error)


OUTPUT_KEYS = frozenset({"decision", "label", "candidate_id", "selection_confidence", "evidence_ids",
                         "abstain_reason"})


@dataclass(frozen=True)
class SemanticResult:
    """A validated outcome. Only an ACCEPTED result carries a label (`usable_label`). Identity (`result_id`,
    `decision_digest`) excludes presentation order, the prompt hash, latency and cost."""

    request_hash: str
    prompt_hash: str
    option_set_hash: str
    task: Task
    task_version: str
    event_id: str
    provider: Provider
    model_version: str
    cutoff_utc: datetime
    evidence_hashes: tuple[tuple[str, str], ...]
    status: Status
    label: str | None
    candidate_id: str | None
    selection_confidence: Decimal | None
    cited_evidence_ids: tuple[str, ...]
    abstain_reason: AbstainReason | None
    rejection: Rejection | None
    detail: str
    latency_ms: int | None
    cost: CostBasis
    estimated_input_tokens: int
    evidence_class: EvidenceClass = RESULT_EVIDENCE_CLASS
    confidence_semantics: str = CONFIDENCE_SEMANTICS
    validator_version: str = VALIDATOR_VERSION

    def __post_init__(self) -> None:
        if self.evidence_class is not RESULT_EVIDENCE_CLASS:
            raise ValueError("every semantic result of this tranche is FIXTURE; a measured class needs an approved "
                             "provider trial (ADR 0049)")
        if self.confidence_semantics != CONFIDENCE_SEMANTICS:
            raise ValueError("selection confidence is not an outcome probability")
        answered = (self.label, self.candidate_id, self.selection_confidence)
        if self.status is Status.ACCEPTED:
            ok = self.label is not None and self.selection_confidence is not None and \
                self.abstain_reason is None and self.rejection is None
        elif self.status is Status.ABSTAINED:
            ok = answered == (None, None, None) and self.abstain_reason is not None and self.rejection is None
        else:
            ok = answered == (None, None, None) and self.rejection is not None and self.abstain_reason is None
        if not ok:
            raise ValueError(f"inconsistent {self.status.value} result")

    @property
    def usable_label(self) -> str | None:
        return self.label if self.status is Status.ACCEPTED else None

    @property
    def decision_digest(self) -> str:
        return payload_sha256({
            "task": self.task.value, "task_version": self.task_version, "status": self.status.value,
            "label": self.label, "candidate_id": self.candidate_id,
            "selection_confidence": None if self.selection_confidence is None else str(self.selection_confidence),
            "cited_evidence_ids": list(self.cited_evidence_ids),
            "abstain_reason": None if self.abstain_reason is None else self.abstain_reason.value,
            "rejection": None if self.rejection is None else self.rejection.value})

    @property
    def result_id(self) -> str:
        return payload_sha256({"request_hash": self.request_hash, "decision_digest": self.decision_digest,
                               "provider": self.provider.value, "model_version": self.model_version,
                               "validator_version": self.validator_version})

    def to_dict(self) -> dict:
        return {
            "result_id": self.result_id, "request_hash": self.request_hash, "prompt_hash": self.prompt_hash,
            "option_set_hash": self.option_set_hash, "task": self.task.value, "task_version": self.task_version,
            "event_id": self.event_id, "provider": self.provider.value, "model_version": self.model_version,
            "cutoff_utc": _iso(self.cutoff_utc), "evidence_hashes": [list(p) for p in self.evidence_hashes],
            "status": self.status.value, "label": self.label, "candidate_id": self.candidate_id,
            "selection_confidence": None if self.selection_confidence is None else str(self.selection_confidence),
            "confidence_semantics": self.confidence_semantics,
            "cited_evidence_ids": list(self.cited_evidence_ids),
            "abstain_reason": None if self.abstain_reason is None else self.abstain_reason.value,
            "rejection": None if self.rejection is None else self.rejection.value, "detail": self.detail,
            "latency_ms": self.latency_ms, "cost": self.cost.to_dict(),
            "estimated_input_tokens": self.estimated_input_tokens, "evidence_class": self.evidence_class.value,
            "measured_accuracy": False, "notice": FIXTURE_NOTICE, "validator_version": self.validator_version,
            "schema_version": SCHEMA_VERSION}


class _Reject(Exception):
    def __init__(self, code: Rejection, detail: str):
        super().__init__(detail)
        self.code = code
        self.detail = detail


def _no_constant(name: str) -> Any:
    raise _Reject(Rejection.MALFORMED_OUTPUT, f"non-finite JSON constant {name}")


def _no_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict:
    keys = [k for k, _ in pairs]
    if len(set(keys)) != len(keys):
        raise _Reject(Rejection.MALFORMED_OUTPUT, "duplicate JSON key")
    return dict(pairs)


def _parse(raw: Any) -> Mapping[str, Any]:
    if isinstance(raw, (bytes, bytearray)):
        try:
            raw = bytes(raw).decode("utf-8")
        except UnicodeDecodeError as exc:
            raise _Reject(Rejection.MALFORMED_OUTPUT, "output is not UTF-8") from exc
    if isinstance(raw, str):
        try:
            raw = json.loads(raw, parse_float=Decimal, parse_constant=_no_constant,
                             object_pairs_hook=_no_duplicate_keys)
        except _Reject:
            raise
        except ValueError as exc:
            raise _Reject(Rejection.MALFORMED_OUTPUT, "output is not JSON") from exc
    if not isinstance(raw, Mapping):
        raise _Reject(Rejection.MALFORMED_OUTPUT, f"output is a {type(raw).__name__}, not an object")
    return raw


def parse_confidence(value: Any) -> Decimal:
    """A finite number in [0, 1], quantized. Strings, booleans, NaN and infinities are refused."""
    if isinstance(value, bool) or not isinstance(value, (int, float, Decimal)):
        raise _Reject(Rejection.INVALID_CONFIDENCE, f"confidence {_short(value)} is not a number")
    if isinstance(value, float):
        if not math.isfinite(value):
            raise _Reject(Rejection.INVALID_CONFIDENCE, f"confidence {_short(value)} is not finite")
        value = Decimal(repr(value))
    elif isinstance(value, int):
        value = Decimal(value)
    if not value.is_finite():
        raise _Reject(Rejection.INVALID_CONFIDENCE, f"confidence {_short(value)} is not finite")
    if not Decimal(0) <= value <= Decimal(1):
        raise _Reject(Rejection.INVALID_CONFIDENCE, f"confidence {_short(value)} is outside [0, 1]")
    return value.quantize(CONFIDENCE_QUANTUM, rounding=ROUND_HALF_EVEN)


def _over_budget(request: SemanticRequest, response: ProviderResponse) -> tuple[AbstainReason, str] | None:
    budget = request.budget
    metered = response.cost.kind is CostKind.PROVIDER_METERED
    if response.latency_ms is None:
        if metered:
            return AbstainReason.TIMEOUT, "latency unmeasured for a metered call"
    elif response.latency_ms > budget.max_latency_ms:
        return AbstainReason.TIMEOUT, f"latency {response.latency_ms} ms over {budget.max_latency_ms} ms"
    cost = response.cost
    for name, used, cap in (("input_tokens", cost.input_tokens, budget.max_input_tokens),
                            ("output_tokens", cost.output_tokens, budget.max_output_tokens),
                            ("monetary_usd", cost.monetary_usd, budget.max_cost_usd)):
        if used is None:
            if metered:
                return AbstainReason.OVER_BUDGET, f"{name} unknown: cannot show it is within budget"
        elif used > cap:
            return AbstainReason.OVER_BUDGET, f"{name} {used} over {cap}"
    return None


def _result(request: SemanticRequest, response: ProviderResponse | None, *, status: Status,
            label: str | None = None, candidate_id: str | None = None, confidence: Decimal | None = None,
            cited: Iterable[str] = (), abstain: AbstainReason | None = None, rejection: Rejection | None = None,
            detail: str = "") -> SemanticResult:
    cost = response.cost if response is not None else CostBasis(CostKind.NO_MODEL_CALL)  # preflight: nothing ran
    return SemanticResult(
        request_hash=request.request_hash, prompt_hash=request.prompt_hash, option_set_hash=request.option_set_hash,
        task=request.task, task_version=request.task_version, event_id=request.event_id, provider=request.provider,
        model_version=str(request.model_version), cutoff_utc=request.cutoff_utc,
        evidence_hashes=tuple(sorted((e.evidence_id, e.content_sha256) for e in request.evidence)),
        status=status, label=label, candidate_id=candidate_id, selection_confidence=confidence,
        cited_evidence_ids=tuple(sorted(set(cited))), abstain_reason=abstain, rejection=rejection, detail=detail,
        latency_ms=None if response is None else response.latency_ms, cost=cost,
        estimated_input_tokens=request.estimated_input_tokens())


def preflight(request: SemanticRequest) -> SemanticResult | None:
    """Abstain before any call when the rendered request cannot fit the input budget."""
    estimate = request.estimated_input_tokens()
    if estimate > request.budget.max_input_tokens:
        return _result(request, None, status=Status.ABSTAINED, abstain=AbstainReason.OVER_BUDGET,
                       detail=f"estimated {estimate} input tokens over {request.budget.max_input_tokens}")
    return None


def validate_response(request: SemanticRequest, response: ProviderResponse) -> SemanticResult:
    """Deterministic validation. Never raises on untrusted output: a bad output is a REJECTED result, a timeout,
    error or over-budget response is ABSTAINED, and only a fully valid answer is ACCEPTED."""
    if not isinstance(response, ProviderResponse):
        raise TypeError("response must be a ProviderResponse")
    early = preflight(request)
    if early is not None:
        return early
    if response.cost.kind is not _PROVIDER_COST_KIND[request.provider]:
        return _result(request, response, status=Status.REJECTED, rejection=Rejection.COST_BASIS_MISMATCH,
                       detail=f"{request.provider.value} responses are {_PROVIDER_COST_KIND[request.provider].value}")
    if response.timed_out:
        return _result(request, response, status=Status.ABSTAINED, abstain=AbstainReason.TIMEOUT, detail="timed out")
    if response.error is not None:
        return _result(request, response, status=Status.ABSTAINED, abstain=AbstainReason.PROVIDER_ERROR,
                       detail=_short(response.error))
    over = _over_budget(request, response)
    if over is not None:
        return _result(request, response, status=Status.ABSTAINED, abstain=over[0], detail=over[1])
    try:
        return _validate_output(request, response, _parse(response.raw_output))
    except _Reject as exc:
        return _result(request, response, status=Status.REJECTED, rejection=exc.code, detail=exc.detail)


def _validate_output(request: SemanticRequest, response: ProviderResponse, out: Mapping[str, Any]) -> SemanticResult:
    keys = set(out)
    if keys != OUTPUT_KEYS:
        extra, missing = sorted(map(str, keys - OUTPUT_KEYS)), sorted(OUTPUT_KEYS - keys)
        raise _Reject(Rejection.SCHEMA_KEYS, f"unexpected keys {_short(extra)}, missing {missing}")
    evidence_ids = out["evidence_ids"]
    if not isinstance(evidence_ids, list) or not all(isinstance(e, str) for e in evidence_ids):
        raise _Reject(Rejection.MALFORMED_OUTPUT, "evidence_ids must be a list of strings")
    unknown = sorted(set(evidence_ids) - request.evidence_ids)
    if unknown:
        raise _Reject(Rejection.EVIDENCE_NOT_ADMITTED, f"cites evidence that was not admitted: {_short(unknown)}")
    decision = out["decision"]
    if decision == "ABSTAIN":
        if (out["label"], out["candidate_id"], out["selection_confidence"]) != (None, None, None):
            raise _Reject(Rejection.INCONSISTENT_DECISION, "an abstention carries no label, candidate or confidence")
        reason = out["abstain_reason"]
        valid = {r.value: r for r in RESPONDER_ABSTAIN_REASONS}
        if not isinstance(reason, str) or reason not in valid:
            raise _Reject(Rejection.INVALID_ABSTAIN_REASON, f"abstain_reason {_short(reason)}")
        return _result(request, response, status=Status.ABSTAINED, abstain=valid[reason], cited=evidence_ids,
                       detail="responder abstained")
    if decision != "ANSWER":
        raise _Reject(Rejection.UNKNOWN_DECISION, f"decision {_short(decision)}")
    if out["abstain_reason"] is not None:
        raise _Reject(Rejection.INCONSISTENT_DECISION, "an answer carries no abstain_reason")
    label = out["label"]
    if not isinstance(label, str) or label not in request.allowed_labels:
        raise _Reject(Rejection.UNKNOWN_LABEL, f"label {_short(label)} is not in {sorted(request.allowed_labels)}")
    confidence = parse_confidence(out["selection_confidence"])
    candidate = out["candidate_id"]
    if label in request.spec.candidate_labels:
        if candidate is None:
            raise _Reject(Rejection.CANDIDATE_REQUIRED, f"{label} names one candidate")
        if not isinstance(candidate, str) or candidate not in request.candidate_ids:
            raise _Reject(Rejection.INVALID_CANDIDATE, f"candidate {_short(candidate)} is not an offered option")
    elif candidate is not None:
        raise _Reject(Rejection.CANDIDATE_FORBIDDEN, f"{label} names no candidate")
    if not evidence_ids:
        raise _Reject(Rejection.EVIDENCE_NOT_CITED, "an answer cites at least one admitted evidence item")
    return _result(request, response, status=Status.ACCEPTED, label=label, candidate_id=candidate,
                   confidence=confidence, cited=evidence_ids)


def permutation_consistent(results: Sequence[SemanticResult]) -> bool:
    """True when every result for one question (one `request_hash`, any option order) made the same decision.
    A position-biased responder fails this; the protocol counts an inconsistent set as abstained."""
    if not results or len({r.request_hash for r in results}) != 1:
        raise ValueError("permutation consistency compares results for one request_hash")
    return len({r.decision_digest for r in results}) == 1


