@dataclass(frozen=True)
class Budget:
    max_input_tokens: int
    max_output_tokens: int
    max_latency_ms: int
    max_cost_usd: Decimal

    def __post_init__(self) -> None:
        for name, value in (("max_input_tokens", self.max_input_tokens),
                            ("max_output_tokens", self.max_output_tokens), ("max_latency_ms", self.max_latency_ms)):
            if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
                raise SemanticValidationError(Rejection.BAD_BUDGET, f"{name} must be a positive integer")
        if not isinstance(self.max_cost_usd, Decimal) or not self.max_cost_usd.is_finite() or self.max_cost_usd < 0:
            raise SemanticValidationError(Rejection.BAD_BUDGET, "max_cost_usd must be a finite Decimal >= 0")

    def identity(self) -> dict:
        return {"max_input_tokens": self.max_input_tokens, "max_output_tokens": self.max_output_tokens,
                "max_latency_ms": self.max_latency_ms, "max_cost_usd": str(self.max_cost_usd)}


@dataclass(frozen=True)
class SemanticRequest:
    """One typed question for one pinned responder. `candidates` is in presentation order; the request's identity
    (`request_hash`) does not depend on that order, the exact rendered prompt (`prompt_hash`) does."""

    task: Task
    task_version: str
    event_id: str  # the candidate event this triage serves (e.g. a market's event ticker)
    subject_evidence_id: str
    candidates: tuple[Candidate, ...]
    evidence: tuple[EvidenceRef, ...]
    cutoff_utc: datetime
    provider: Provider
    model_version: str | None
    allowed_labels: frozenset[str]
    budget: Budget
    schema_version: str = SCHEMA_VERSION

    def __post_init__(self) -> None:
        if self.schema_version != SCHEMA_VERSION:
            raise SemanticValidationError(Rejection.UNKNOWN_SCHEMA_VERSION, _short(self.schema_version))
        if not isinstance(self.task, Task):
            raise SemanticValidationError(Rejection.BAD_TYPE, "task must be a Task")
        spec = TASK_SPECS[self.task]
        if self.task_version != spec.version:
            raise SemanticValidationError(Rejection.UNKNOWN_TASK_VERSION,
                                          f"{self.task.value} is {spec.version}, got {_short(self.task_version)}")
        labels = frozenset(self.allowed_labels)
        if labels != spec.labels:
            raise SemanticValidationError(Rejection.LABEL_SET_MISMATCH,
                                          f"{self.task.value} labels are {sorted(spec.labels)}")
        object.__setattr__(self, "allowed_labels", labels)
        if not isinstance(self.provider, Provider):
            raise SemanticValidationError(Rejection.BAD_TYPE, "provider must be a Provider")
        if self.model_version not in PINNED_MODEL_VERSIONS[self.provider]:
            raise SemanticValidationError(Rejection.UNKNOWN_MODEL_VERSION,
                                          f"{self.provider.value} has no pinned version {_short(self.model_version)}")
        _require_id(self.event_id, "event_id")
        _require_id(self.subject_evidence_id, "subject_evidence_id")
        if not isinstance(self.budget, Budget):
            raise SemanticValidationError(Rejection.BAD_BUDGET, "budget must be a Budget")
        object.__setattr__(self, "cutoff_utc", _utc(self.cutoff_utc, "cutoff_utc"))
        candidates = tuple(self.candidates)
        if not candidates:
            raise SemanticValidationError(Rejection.NO_CANDIDATES, "a request needs at least one candidate")
        if not all(isinstance(c, Candidate) for c in candidates):
            raise SemanticValidationError(Rejection.BAD_TYPE, "candidates must be Candidate values")
        if len({c.candidate_id for c in candidates}) != len(candidates):
            raise SemanticValidationError(Rejection.DUPLICATE_ID, "candidate ids must be unique")
        object.__setattr__(self, "candidates", candidates)
        evidence = tuple(self.evidence)
        if not evidence:
            raise SemanticValidationError(Rejection.MISSING_EVIDENCE, "a request needs admitted evidence")
        if not all(isinstance(e, EvidenceRef) for e in evidence):
            raise SemanticValidationError(Rejection.BAD_TYPE, "evidence must be EvidenceRef values")
        if len({e.evidence_id for e in evidence}) != len(evidence):
            raise SemanticValidationError(Rejection.DUPLICATE_ID, "evidence ids must be unique")
        future = sorted(e.evidence_id for e in evidence if e.first_receipt_utc > self.cutoff_utc)
        if future:
            raise SemanticValidationError(Rejection.FUTURE_EVIDENCE, f"received after the cutoff: {future}")
        object.__setattr__(self, "evidence", evidence)
        if self.subject_evidence_id not in {e.evidence_id for e in evidence}:
            raise SemanticValidationError(Rejection.SUBJECT_NOT_ADMITTED,
                                          f"subject {self.subject_evidence_id} is not admitted evidence")

    @property
    def spec(self) -> TaskSpec:
        return TASK_SPECS[self.task]

    @property
    def candidate_ids(self) -> frozenset[str]:
        return frozenset(c.candidate_id for c in self.candidates)

    @property
    def evidence_ids(self) -> frozenset[str]:
        return frozenset(e.evidence_id for e in self.evidence)

    @property
    def presentation_order(self) -> tuple[str, ...]:
        return tuple(c.candidate_id for c in self.candidates)

    @property
    def subject(self) -> EvidenceRef:
        return next(e for e in self.evidence if e.evidence_id == self.subject_evidence_id)

    @property
    def option_set_hash(self) -> str:
        return payload_sha256(sorted((c.identity() for c in self.candidates), key=lambda d: d["candidate_id"]))

    @property
    def request_hash(self) -> str:
        """Order-independent identity of the question asked."""
        return payload_sha256({
            "schema_version": self.schema_version, "task": self.task.value, "task_version": self.task_version,
            "event_id": self.event_id, "subject_evidence_id": self.subject_evidence_id,
            "option_set_hash": self.option_set_hash,
            "evidence": sorted((e.identity() for e in self.evidence), key=lambda d: d["evidence_id"]),
            "cutoff_utc": _iso(self.cutoff_utc), "provider": self.provider.value,
            "model_version": self.model_version, "allowed_labels": sorted(self.allowed_labels),
            "budget": self.budget.identity()})

    def render(self) -> dict:
        """The exact payload a responder would see. Fixed text first; retrieved text only under `untrusted_data`."""
        return {
            "render_version": RENDER_VERSION, "header": RENDER_HEADER, "task": self.task.value,
            "task_version": self.task_version, "instruction": TASK_INSTRUCTIONS[self.task],
            "allowed_labels": sorted(self.allowed_labels),
            "abstain_reasons": sorted(r.value for r in RESPONDER_ABSTAIN_REASONS),
            "event_id": self.event_id, "subject_evidence_id": self.subject_evidence_id,
            "options": [{"candidate_id": c.candidate_id, "text": c.text} for c in self.candidates],
            "untrusted_data": [{"evidence_id": e.evidence_id, "source_id": e.source_id,
                                "content_sha256": e.content_sha256, "text": e.text}
                               for e in sorted(self.evidence, key=lambda e: e.evidence_id)],
        }

    @property
    def prompt_hash(self) -> str:
        return payload_sha256(self.render())

    def estimated_input_tokens(self) -> int:
        size = len(json.dumps(self.render(), sort_keys=True, ensure_ascii=False).encode("utf-8"))
        return -(-size // ESTIMATE_BYTES_PER_TOKEN)


