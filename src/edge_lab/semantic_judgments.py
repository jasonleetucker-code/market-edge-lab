class SemanticValidationError(ValueError):
    """A value that cannot be built. `code` is the deterministic reason."""

    def __init__(self, code: Rejection, detail: str):
        super().__init__(f"{code.value}: {detail}")
        self.code = code
        self.detail = detail


_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.:\-]{0,127}")
_SHA256 = re.compile(r"[0-9a-f]{64}")


def _require_id(value: Any, what: str) -> str:
    if not isinstance(value, str) or not _ID.fullmatch(value):
        raise SemanticValidationError(Rejection.BAD_IDENTIFIER, f"{what} {_short(value)} is not a valid identifier")
    return value


def _require_sha(value: Any, what: str) -> str:
    if not isinstance(value, str) or not _SHA256.fullmatch(value):
        raise SemanticValidationError(Rejection.BAD_HASH, f"{what} is not a lowercase sha256 hex digest")
    return value


def _utc(value: Any, what: str) -> datetime:
    if not isinstance(value, datetime) or value.tzinfo is None or value.utcoffset() is None:
        raise SemanticValidationError(Rejection.NAIVE_TIME, f"{what} must be a timezone-aware datetime")
    return value.astimezone(timezone.utc)


def _iso(value: datetime | None) -> str | None:
    return None if value is None else value.isoformat()


def _short(value: Any) -> str:
    text = repr(value)
    return text if len(text) <= 80 else text[:77] + "..."


def _claims(value: Iterable[Any], what: str) -> tuple[tuple[str, str], ...]:
    out = []
    for pair in value:
        if not (isinstance(pair, tuple) and len(pair) == 2 and all(isinstance(p, str) and p for p in pair)):
            raise SemanticValidationError(Rejection.BAD_TYPE, f"{what} claims must be (key, value) string pairs")
        out.append(pair)
    return tuple(sorted(set(out)))


def _keys(value: Iterable[Any], what: str) -> frozenset[str]:
    keys = frozenset(value)
    if not all(isinstance(k, str) and k for k in keys):
        raise SemanticValidationError(Rejection.BAD_TYPE, f"{what} keys must be non-empty strings")
    return keys


