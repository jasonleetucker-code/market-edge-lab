"""Typed semantic-triage judgments: provider-neutral request/result value types (#181 Deliverable F, ADR 0049).

**What this module is.** Versioned value types and deterministic validation for exactly four bounded tasks:

1. `RELEVANCE`: is an evidence item relevant to one candidate event or source?
2. `DUPLICATE`: is an item a duplicate of a candidate story, or an original?
3. `CONTRADICTION`: does a candidate claim contradict the item, so that a human must verify it?
4. `TERM_AMBIGUITY`: is a contract-term clause ambiguous? **For human review only, never settlement verification.**

It also holds two benchmark responders that make no model call: deterministic rules (`rules_baseline`) and a
non-generative token-containment scorer (`non_generative_baseline`). The prospective protocol
(`docs/research/SEMANTIC_TRIAGE_PROTOCOL.md`) benchmarks both before any model.

**Fixture-only, zero model calls.** There is no provider integration, no SDK and no network code. A response is a
plain value (`ProviderResponse`) that a test or a baseline builds. `JEV` and `KEV` are named providers with no pinned
model version, so a request addressed to either fails validation (`UNKNOWN_MODEL_VERSION`) until a separately
approved trial pins one. Every result is labelled FIXTURE (`RESULT_EVIDENCE_CLASS`) and is never a measured Jev/Kev
accuracy.

**What a result may never be.** An LLM may classify, extract, summarize and criticize. It is never the source of a
price, fee, payoff, settlement rule, timestamp, position, size or risk limit (AI_INSTRUCTIONS.md;
RESEARCH_PRINCIPLES.md, "The LLM boundary"). The output schema is closed: any key outside `OUTPUT_KEYS` rejects the whole output. The
confidence a responder reports is **selection confidence** (how sure it is of the label it chose), never the
probability of a real-world outcome (`CONFIDENCE_SEMANTICS`).

**Retrieved text is untrusted data.** It is carried as data, rendered under `untrusted_data`, and never changes the
task, the label set, the candidates, the budget or the provider. Labels come only from `TASK_SPECS`. A response that
follows an injected instruction can produce only an allowed label or a rejection.

**Point in time.** Evidence is admitted by our own first-receipt time (`first_receipt_utc <= cutoff_utc`). An
upstream's claimed publication time is untrusted and never admits anything.

**Lane SE.** The change/event envelope belongs to the crawler lane (`sources`/provenance/freshness owners). This
module references it only by id or hash (`EvidenceRef.envelope_ref`) and imports none of its types.

Deterministic, stdlib-only, no I/O. The only `edge_lab` import is `provenance` (content hashing).
"""

