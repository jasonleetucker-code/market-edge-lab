@dataclass(frozen=True)
class EvidenceRef:
    """One admitted evidence item. `text` is untrusted retrieved content, carried as data only.

    `keys` and `claims` come from deterministic extraction (a versioned parser), never from a model.
    `envelope_ref` is the id or hash of lane SE's change envelope, when one exists; nothing else of it is used.
    `upstream_published_utc` is what the upstream claims; it is recorded and never used for admission.
    """

    evidence_id: str
    source_id: str
    content_sha256: str
    first_receipt_utc: datetime
    evidence_class: EvidenceClass
    text: str | None = None
    keys: frozenset[str] = frozenset()
    claims: tuple[tuple[str, str], ...] = ()
    envelope_ref: str | None = None
    upstream_published_utc: datetime | None = None

    def __post_init__(self) -> None:
        _require_id(self.evidence_id, "evidence_id")
        _require_id(self.source_id, "source_id")
        _require_sha(self.content_sha256, f"evidence {self.evidence_id} content_sha256")
        if not isinstance(self.evidence_class, EvidenceClass):
            raise SemanticValidationError(Rejection.BAD_TYPE, "evidence_class must be an EvidenceClass")
        if self.text is not None:
            if not isinstance(self.text, str):
                raise SemanticValidationError(Rejection.BAD_TYPE, "text must be a string or None")
            if sha256_hex(self.text) != self.content_sha256:
                raise SemanticValidationError(Rejection.HASH_MISMATCH,
                                              f"evidence {self.evidence_id}: text does not match content_sha256")
        if self.envelope_ref is not None:
            _require_id(self.envelope_ref, "envelope_ref")
        object.__setattr__(self, "first_receipt_utc", _utc(self.first_receipt_utc, "first_receipt_utc"))
        if self.upstream_published_utc is not None:
            object.__setattr__(self, "upstream_published_utc",
                               _utc(self.upstream_published_utc, "upstream_published_utc"))
        object.__setattr__(self, "keys", _keys(self.keys, f"evidence {self.evidence_id}"))
        object.__setattr__(self, "claims", _claims(self.claims, f"evidence {self.evidence_id}"))

    @classmethod
    def from_text(cls, evidence_id: str, source_id: str, text: str, first_receipt_utc: datetime,
                  evidence_class: EvidenceClass = EvidenceClass.FIXTURE, **kwargs: Any) -> "EvidenceRef":
        return cls(evidence_id, source_id, sha256_hex(text), first_receipt_utc, evidence_class, text=text, **kwargs)

    def identity(self) -> dict:
        """Hash inputs. The text is covered by `content_sha256`."""
        return {"evidence_id": self.evidence_id, "source_id": self.source_id, "content_sha256": self.content_sha256,
                "first_receipt_utc": _iso(self.first_receipt_utc), "evidence_class": self.evidence_class.value,
                "keys": sorted(self.keys), "claims": [list(c) for c in self.claims],
                "envelope_ref": self.envelope_ref, "upstream_published_utc": _iso(self.upstream_published_utc)}


@dataclass(frozen=True)
class Candidate:
    """One option: a candidate event or source (RELEVANCE), story (DUPLICATE), claim (CONTRADICTION) or contract
    clause (TERM_AMBIGUITY). `text` is still data when rendered."""

    candidate_id: str
    text: str
    keys: frozenset[str] = frozenset()
    claims: tuple[tuple[str, str], ...] = ()
    ref_sha256: str | None = None  # hash of the candidate's own source record (story body, rules snapshot)

    def __post_init__(self) -> None:
        _require_id(self.candidate_id, "candidate_id")
        if not isinstance(self.text, str):
            raise SemanticValidationError(Rejection.BAD_TYPE, "candidate text must be a string")
        if self.ref_sha256 is not None:
            _require_sha(self.ref_sha256, f"candidate {self.candidate_id} ref_sha256")
        object.__setattr__(self, "keys", _keys(self.keys, f"candidate {self.candidate_id}"))
        object.__setattr__(self, "claims", _claims(self.claims, f"candidate {self.candidate_id}"))

    def identity(self) -> dict:
        return {"candidate_id": self.candidate_id, "text_sha256": sha256_hex(self.text), "keys": sorted(self.keys),
                "claims": [list(c) for c in self.claims], "ref_sha256": self.ref_sha256}


def admit_evidence(items: Iterable[EvidenceRef], cutoff_utc: datetime
                   ) -> tuple[tuple[EvidenceRef, ...], tuple[tuple[str, Rejection], ...]]:
    """Partition by our own first-receipt time. Received after the cutoff means not admitted, whatever the
    upstream claims about publication."""
    cutoff = _utc(cutoff_utc, "cutoff_utc")
    admitted, excluded = [], []
    for item in items:
        if item.first_receipt_utc <= cutoff:
            admitted.append(item)
        else:
            excluded.append((item.evidence_id, Rejection.FUTURE_EVIDENCE))
    return tuple(admitted), tuple(excluded)


